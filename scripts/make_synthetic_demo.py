@dataclass
class DemoResult:
    session_id: str
    out_dir: Path
    nodes: list[int]
    origin: dict[str, float]
    destination: dict[str, float]
    drive_length_m: float
    speed_mps: float
    duration_s: float
    n_inserted: int
    n_found: int | None  # None when not processed
    n_extra_tracks: int | None
    routes_differ: bool | None  # None when not verified
    candidates_tried: int
    notes: list[str] = field(default_factory=list)


def _street(graph: RoadGraph, nodes: list[int]) -> str | None:
    for a, b in zip(nodes, nodes[1:]):
        key, _ = _edge_choice(graph, a, b)
        name = graph.g[a][b][key].get("name")
        if name:
            return name
    return None


def count_found(
    conn, session_id: str, schedule: Schedule, tolerance_s: float = 0.6
) -> tuple[int, int]:
    """``(inserted pothole images found, tracks matching no inserted image)``."""
    rows = obs_db.list_observations(conn, session_id)
    spans = [
        (schedule.pothole_start(i) / schedule.fps, (schedule.pothole_start(i) + schedule.hold) / schedule.fps)
        for i in range(schedule.n)
    ]

    def overlaps(o: dict[str, Any], span: tuple[float, float]) -> bool:
        first = o["first_t_video_s"] if o["first_t_video_s"] is not None else o["t_video_s"]
        return first <= span[1] + tolerance_s and o["t_video_s"] >= span[0] - tolerance_s

    found = sum(1 for span in spans if any(overlaps(o, span) for o in rows))
    extra = sum(1 for o in rows if not any(overlaps(o, span) for span in spans))
    return found, extra


def routes_differ(
    conn, graph: RoadGraph, cfg: AppConfig, origin: LatLon, destination: LatLon
) -> tuple[bool, str]:
    """Whether avoidance 0 and avoidance 1 give different routes, with a short explanation."""
    try:
        plan = plan_routes(conn, graph, origin, destination, 1.0, cfg.routing, cfg.mapping)
    except RoutingError as exc:
        return False, f"routing failed: {exc}"
    same = any(LABEL_SHORTEST in r["labels"] and LABEL_STRONGEST in r["labels"] for r in plan["routes"])
    shortest = next(r for r in plan["routes"] if LABEL_SHORTEST in r["labels"])
    fewest = next(r for r in plan["routes"] if LABEL_STRONGEST in r["labels"])
    text = (
        f"shortest {shortest['distance_m']:.0f} m with {shortest['expected_potholes_total']:.1f} "
        f"estimated potholes; strongest-avoidance {fewest['distance_m']:.0f} m with "
        f"{fewest['expected_potholes_total']:.1f} estimated"
    )
    return (not same), text


def _remove_previous(conn, cfg: AppConfig) -> list[str]:
    ids = [
        r[0]
        for r in conn.execute(
            "SELECT id FROM sessions WHERE name = ? AND role = 'demo' AND gps_source = 'synthetic'",
            (SESSION_NAME,),
        )
    ]
    for sid in ids:
        delete_session(conn, sid)
        delete_session_files(cfg, sid)
    conn.commit()
    return ids


def run_demo(
    cfg: AppConfig,
    *,
    seed: int = 7,
    n_potholes: int = 13,
    process: bool = True,
    detector_factory: Callable[[], Any] | None = None,
    dataset_dir: Path | None = None,
    out_dir: Path | None = None,
    max_candidates: int = 6,
    max_alt_ratio: float = 1.6,
    log: Callable[[str], None] = print,
) -> DemoResult:
    """Generate, register and (unless ``process`` is False) process and verify the demo."""
    graph, graph_error = load_configured_graph(cfg)
    if graph is None:
        reason = graph_error or f"no file at {cfg.routing.graph_path}"
        raise DemoError(
            f"a road graph is needed ({reason}); create one with "
            "'python -m roadsense.routing.graph --bbox ...'"
        )
    dataset_dir = dataset_dir or (cfg.data_dir / DATASET_SUBDIR)
    out_dir = out_dir or (cfg.data_dir / "demo")

    schedule = make_schedule(n_potholes, cfg.tracking)
    positives, negatives = list_val_images(dataset_dir, min_positives=n_potholes)
    potholes, fillers = choose_images(positives, negatives, n_potholes, schedule.n_filler_segments(), seed)
    log(
        f"{n_potholes} pothole images + {len(set(fillers))} pothole-free images from the validation "
        f"split; {schedule.total_frames} frames at {schedule.fps:g} fps = {schedule.duration_s:.1f} s"
    )

    candidates = find_candidates(graph, schedule, seed=seed, max_alt_ratio=max_alt_ratio)
    if not candidates:
        raise DemoError(
            "no suitable drive found in the road graph: need a shortest path of about "
            f"{NOMINAL_SPEED_MPS * (schedule.duration_s + 2):.0f} m that has an alternative route "
            f"over its first part (at most {max_alt_ratio:g} times as long)"
        )
    log(f"{len(candidates)} candidate drive(s) in the road graph")

    video_path = out_dir / f"{SESSION_NAME}.mp4"
    gps_path = out_dir / f"{SESSION_NAME}_gps.csv"
    sidecar_path = out_dir / f"{SESSION_NAME}.json"
    write_video(video_path, schedule, potholes, fillers)

    try:  # refuses to run while the web server is using this database
        lock = ProcessLock(lock_path_for(cfg.db_path), role="demo script").acquire()
    except AlreadyRunningError as exc:
        raise DemoError(str(exc)) from None
    conn = db.connect(cfg.db_path)
    try:
        db.init_schema(conn)
        removed = _remove_previous(conn, cfg)
        if removed:
            log(f"replaced {len(removed)} earlier synthetic demo session(s)")
        notes: list[str] = []
        detector = None
        tried = 0
        result: DemoResult | None = None
        limit = min(max_candidates, len(candidates)) if process else 1
        for cand in candidates[:limit]:
            tried += 1
            fixes, speed = generate_fixes(cand.points, schedule.duration_s)
            write_gps_csv(gps_path, fixes)
            write_sidecar(
                sidecar_path, video_path.name, gps_path.name, schedule.duration_s, len(fixes), cand.length_m
            )
            session_id = create_session_from_files(
                conn, cfg, video=video_path, gps=gps_path, sidecar=sidecar_path,
                name=SESSION_NAME, role="demo", gps_source="synthetic",
            )  # fmt: skip
            conn.commit()
            dest_node = graph.g.nodes[cand.nodes[cand.dest_index]]
            origin_node = graph.g.nodes[cand.nodes[0]]
            origin = {"lat": origin_node["lat"], "lon": origin_node["lon"]}
            destination = {"lat": dest_node["lat"], "lon": dest_node["lon"]}
            result = DemoResult(
                session_id=session_id, out_dir=out_dir, nodes=cand.nodes, origin=origin,
                destination=destination, drive_length_m=cand.length_m, speed_mps=speed,
                duration_s=schedule.duration_s, n_inserted=n_potholes, n_found=None,
                n_extra_tracks=None, routes_differ=None, candidates_tried=tried, notes=notes,
            )  # fmt: skip
            if not process:
                notes.append("not processed (--no-process): routes were not verified")
                break
            if detector is None:
                try:
                    detector = detector_factory() if detector_factory else _real_detector(cfg)
                except Exception as exc:
                    raise DemoError(f"the detector could not be loaded: {exc}") from exc
            try:
                process_session(conn, session_id, detector, cfg)
            except PipelineError as exc:
                raise DemoError(f"processing the synthetic session failed: {exc}") from exc
            write_and_rebuild(conn, cfg, graph, include_synthetic=True)
            result.n_found, result.n_extra_tracks = count_found(conn, session_id, schedule)
            differ, text = routes_differ(
                conn, graph, cfg, (origin["lat"], origin["lon"]), (destination["lat"], destination["lon"])
            )
            result.routes_differ = differ
            log(f"candidate {tried}: {text}; routes differ: {differ}")
            if differ:
                break
            if tried < limit:  # try the next candidate with a clean slate
                write_and_rebuild(
                    conn, cfg, graph, include_synthetic=True,
                    before=lambda c, sid=session_id: delete_session(c, sid),
                )  # fmt: skip
                delete_session_files(cfg, session_id)
        assert result is not None
        if process and not result.routes_differ:
            notes.append(
                f"NO candidate drive gave different routes for avoidance 0 and 1 "
                f"({tried} tried); the demonstration session is registered but does not show a "
                "route change"
            )
        _write_demo_route(out_dir, graph, result, schedule)
        return result
    finally:
        conn.close()
        lock.release()


def _real_detector(cfg: AppConfig) -> Any:
    from roadsense.detection.detector import Detector

    return Detector(cfg.detection)


def _write_demo_route(out_dir: Path, graph: RoadGraph, result: DemoResult, schedule: Schedule) -> None:
    street = _street(graph, result.nodes)
    where = f" near {street}" if street else ""
    found = (
        ""
        if result.n_found is None
        else f" The detector found {result.n_found} of them."
    )
    description = (
        f"SYNTHETIC demonstration: {result.n_inserted} pothole images from the RDD2022 validation "
        f"set were placed along a generated drive of about {result.drive_length_m:.0f} m{where}; the "
        f"GPS trace is generated.{found} Compare avoidance 0% and 100%."
    )
    payload = {
        "origin": result.origin,
        "destination": result.destination,
        "description": description,
        "synthetic": True,
        "routes_differ": result.routes_differ,
        "session_id": result.session_id,
    }
    (out_dir / "demo_route.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


