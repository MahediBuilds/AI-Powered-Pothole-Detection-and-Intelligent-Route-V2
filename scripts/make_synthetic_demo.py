FRAME_SIZE = 640  # square frames: the detector sees images near their training scale
BANNER_H = 28
FPS = 10.0
NOMINAL_SPEED_MPS = 8.0  # about 29 km/h; the real speed is the path length over the duration
MIN_SPACING_M = 32.0  # design spacing between potholes; the requirement is 30 m
FREE_FRACTION = 0.75  # pothole-free driving after the potholes, relative to their duration
MIN_BOX_AREA = 0.01  # prefer positive images whose largest pothole box covers this fraction
EPOCH_MS = int(datetime(2026, 1, 1, 12, tzinfo=timezone.utc).timestamp() * 1000)
DATASET_SUBDIR = Path("processed") / "rdd2022_pothole"


class DemoError(Exception):
    """The demonstration cannot be created; the message says why."""


# ---------------------------------------------------------------------------- images


def _read_label_boxes(path: Path) -> list[tuple[float, float]] | None:
    """Normalised (w, h) of the pothole boxes in a YOLO label file; None if it is missing."""
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return None
    boxes = []
    for line in lines:
        parts = line.split()
        if len(parts) == 5 and parts[0] == "0":
            boxes.append((float(parts[3]), float(parts[4])))
    return boxes


def list_val_images(
    dataset_dir: Path, min_box_area: float = MIN_BOX_AREA, min_positives: int = 1
) -> tuple[list[Path], list[Path]]:
    """``(positives, negatives)`` from the VALIDATION split, each sorted by name.

    A positive has at least one pothole box; only images whose largest box covers
    at least ``min_box_area`` of the image are kept, unless that leaves fewer than
    ``min_positives`` (then every positive is kept). A negative has an empty label file.
    """
    images_dir = dataset_dir / "images" / "val"
    labels_dir = dataset_dir / "labels" / "val"
    if not images_dir.is_dir() or not labels_dir.is_dir():
        raise DemoError(
            f"RDD2022 validation images not found under {dataset_dir} "
            "(expected images/val and labels/val); convert the dataset first"
        )
    big, small, negatives = [], [], []
    for image in sorted(p for p in images_dir.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png")):
        boxes = _read_label_boxes(labels_dir / f"{image.stem}.txt")
        if boxes is None:
            continue
        if not boxes:
            negatives.append(image)
        elif max(w * h for w, h in boxes) >= min_box_area:
            big.append(image)
        else:
            small.append(image)
    return (big if len(big) >= min_positives else sorted(big + small)), negatives


def choose_images(
    positives: list[Path], negatives: list[Path], n_potholes: int, n_fillers: int, seed: int
) -> tuple[list[Path], list[Path]]:
    """Deterministically pick ``n_potholes`` pothole images and ``n_fillers`` pothole-free ones."""
    if n_potholes < 1:
        raise DemoError("--n-potholes must be at least 1")
    if len(positives) < n_potholes:
        raise DemoError(
            f"only {len(positives)} validation image(s) with potholes, {n_potholes} requested"
        )
    if not negatives:
        raise DemoError("the validation split has no pothole-free image to separate the potholes")
    rng = random.Random(seed)
    chosen = rng.sample(positives, n_potholes)
    fillers: list[Path] = []
    while len(fillers) < n_fillers:
        batch = rng.sample(negatives, len(negatives))
        if fillers and len(negatives) > 1 and batch[0] == fillers[-1]:
            batch.append(batch.pop(0))
        fillers.extend(batch)
    return chosen, fillers[:n_fillers]


def add_caption(frame: Any, text: str = CAPTION) -> Any:
    """Burn the caption into the top banner of ``frame`` (in place) and return it.

    Yellow text on black, so it stays readable and is never mistaken for road.
    """
    import cv2

    h, w = frame.shape[:2]
    banner = min(BANNER_H, h)
    frame[:banner, :] = 0
    font = cv2.FONT_HERSHEY_SIMPLEX
    scale = 0.5
    while scale > 0.2 and cv2.getTextSize(text, font, scale, 1)[0][0] > w - 8:
        scale -= 0.02
    (tw, th), base = cv2.getTextSize(text, font, scale, 1)
    cv2.putText(frame, text, (4, (banner + th) // 2), font, scale, (0, 255, 255), 1, cv2.LINE_AA)
    return frame


def render_frame(path: Path) -> Any:
    """A square frame: caption banner on top, the image letterboxed below it."""
    import cv2
    import numpy as np

    data = np.fromfile(str(path), dtype=np.uint8)
    image = cv2.imdecode(data, cv2.IMREAD_COLOR) if data.size else None
    if image is None:
        raise DemoError(f"cannot read image {path}")
    area_h = FRAME_SIZE - BANNER_H
    h, w = image.shape[:2]
    scale = min(FRAME_SIZE / w, area_h / h)
    new_w, new_h = max(1, round(w * scale)), max(1, round(h * scale))
    resized = cv2.resize(image, (new_w, new_h), interpolation=cv2.INTER_AREA if scale < 1 else cv2.INTER_LINEAR)
    frame = np.zeros((FRAME_SIZE, FRAME_SIZE, 3), np.uint8)
    x0, y0 = (FRAME_SIZE - new_w) // 2, BANNER_H + (area_h - new_h) // 2
    frame[y0 : y0 + new_h, x0 : x0 + new_w] = resized
    return add_caption(frame)


# ---------------------------------------------------------------------------- schedule


@dataclass(frozen=True)
class Segment:
    kind: str  # "pothole" or "filler"
    start: int  # first frame
    end: int  # one past the last frame
    image: Path


@dataclass(frozen=True)
class Schedule:
    """Frame layout: lead filler, ``n`` x (pothole image, filler), then pothole-free driving."""

    n: int
    fps: float
    hold: int  # frames each pothole image stays on screen
    gap: int  # pothole-free frames after each pothole image
    lead: int
    free: int  # extra pothole-free frames at the end

    @property
    def cycle(self) -> int:
        return self.hold + self.gap

    @property
    def total_frames(self) -> int:
        return self.lead + self.n * self.cycle + self.free

    @property
    def duration_s(self) -> float:
        return self.total_frames / self.fps

    def pothole_start(self, i: int) -> int:
        return self.lead + i * self.cycle

    @property
    def potholes_end_s(self) -> float:
        """Video time at which the last pothole image leaves the screen."""
        return (self.pothole_start(self.n - 1) + self.hold) / self.fps

    def n_filler_segments(self) -> int:
        """How many pothole-free images ``segments`` needs."""
        return 1 + self.n + (math.ceil(self.free / self.gap) if self.free else 0)

    def segments(self, potholes: list[Path], fillers: list[Path]) -> list[Segment]:
        out: list[Segment] = []
        fill = iter(fillers)
        out.append(Segment("filler", 0, self.lead, next(fill)))
        for i, image in enumerate(potholes):
            start = self.pothole_start(i)
            out.append(Segment("pothole", start, start + self.hold, image))
            out.append(Segment("filler", start + self.hold, start + self.cycle, next(fill)))
        pos = self.lead + self.n * self.cycle
        while pos < self.total_frames:
            end = min(pos + self.gap, self.total_frames)
            out.append(Segment("filler", pos, end, next(fill)))
            pos = end
        return out


def make_schedule(
    n_potholes: int,
    tracking: TrackingConfig,
    *,
    fps: float = FPS,
    speed_mps: float = NOMINAL_SPEED_MPS,
    free_fraction: float = FREE_FRACTION,
) -> Schedule:
    """Timing that satisfies the tracker settings and the spacing rule.

    * ``hold``: a static image gives one detection per processed frame, so
      ``min_hits + 3`` processed frames keep it confirmed even if a few are missed.
    * ``gap``: more than ``max_age_frames`` processed frames without a pothole, so a
      track cannot continue from one image into the next.
    * The cycle is also long enough for ``MIN_SPACING_M`` at ``speed_mps``.
    """
    stride = tracking.frame_stride
    hold = stride * (tracking.min_hits + 3)
    min_gap = stride * (tracking.max_age_frames + 2)
    cycle = max(hold + min_gap, math.ceil(MIN_SPACING_M / speed_mps * fps))
    lead = max(min_gap, round(1.5 * fps))
    free = round(free_fraction * n_potholes * cycle)
    return Schedule(n=n_potholes, fps=fps, hold=hold, gap=cycle - hold, lead=lead, free=free)


def write_video(path: Path, schedule: Schedule, potholes: list[Path], fillers: list[Path]) -> None:
    """Render the schedule to an MP4 (each distinct image is rendered once)."""
    import cv2

    path.parent.mkdir(parents=True, exist_ok=True)
    writer = cv2.VideoWriter(
        str(path), cv2.VideoWriter_fourcc(*"mp4v"), schedule.fps, (FRAME_SIZE, FRAME_SIZE)
    )
    if not writer.isOpened():
        writer.release()
        raise DemoError("cannot open an MP4 video writer (OpenCV has no usable mp4v codec)")
    try:
        for seg in schedule.segments(potholes, fillers):
            frame = render_frame(seg.image)
            for _ in range(seg.end - seg.start):
                writer.write(frame)
    finally:
        writer.release()
    if not path.is_file() or path.stat().st_size == 0:
        raise DemoError(f"the video writer produced no data at {path}")


# ---------------------------------------------------------------------------- path and GPS

LatLon = tuple[float, float]


def _weight(u: int, v: int, parallel: dict) -> float:
    return min(d["length_m"] for d in parallel.values())


def _edge_choice(graph: RoadGraph, a: int, b: int) -> tuple[int, list[LatLon]]:
    """The shortest parallel edge a -> b: its key and geometry in the travel direction."""
    key = min(graph.g[a][b], key=lambda k: (graph.g[a][b][k]["length_m"], k))
    return key, list(graph.g[a][b][key]["geometry"])


def polyline_length(points: list[LatLon]) -> float:
    return sum(haversine_m(*p, *q) for p, q in zip(points, points[1:]))


def path_polyline(graph: RoadGraph, nodes: list[int]) -> tuple[list[LatLon], list[float]]:
    """The driven geometry along a node path, and the distance at each node (metres)."""
    points: list[LatLon] = []
    node_index: list[int] = []  # index in ``points`` where each node lies
    for a, b in zip(nodes, nodes[1:]):
        _, geom = _edge_choice(graph, a, b)
        if points and points[-1] == geom[0]:
            geom = geom[1:]
        elif not points:
            node_index.append(0)
        points.extend(geom)
        node_index.append(len(points) - 1)
    cum = [0.0]
    for p, q in zip(points, points[1:]):
        cum.append(cum[-1] + haversine_m(*p, *q))
    return points, [cum[i] for i in node_index]


def bearing_deg(a: LatLon, b: LatLon) -> float:
    lat1, lat2 = math.radians(a[0]), math.radians(b[0])
    dlon = math.radians(b[1] - a[1])
    y = math.sin(dlon) * math.cos(lat2)
    x = math.cos(lat1) * math.sin(lat2) - math.sin(lat1) * math.cos(lat2) * math.cos(dlon)
    return round(math.degrees(math.atan2(y, x)) % 360.0, 1)


class _Along:
    """Position and heading at a distance along a polyline."""

    def __init__(self, points: list[LatLon]) -> None:
        self.points = points
        self.cum = [0.0]
        for p, q in zip(points, points[1:]):
            self.cum.append(self.cum[-1] + haversine_m(*p, *q))
        self.length = self.cum[-1]

    def at(self, s: float) -> tuple[LatLon, float]:
        s = min(max(s, 0.0), self.length)
        i = min(max(bisect_right(self.cum, s) - 1, 0), len(self.points) - 2)
        seg = self.cum[i + 1] - self.cum[i]
        f = 0.0 if seg == 0 else (s - self.cum[i]) / seg
        (la1, lo1), (la2, lo2) = self.points[i], self.points[i + 1]
        return (la1 + f * (la2 - la1), lo1 + f * (lo2 - lo1)), bearing_deg(self.points[i], self.points[i + 1])


def generate_fixes(
    points: list[LatLon], duration_s: float, *, dt: float = 1.0
) -> tuple[list[dict[str, float]], float]:
    """Fixes every ``dt`` s from t = -dt to exactly ``duration_s + dt`` at one constant speed.

    The speed is chosen so that the whole polyline is driven in that time. Returns
    the fixes and the speed in m/s.
    """
    along = _Along(points)
    t_first, t_last = -dt, duration_s + dt
    speed = along.length / (t_last - t_first)
    times = [t_first + k * dt for k in range(int((t_last - t_first) / dt + 1e-9) + 1)]
    if times[-1] < t_last - 1e-9:
        times.append(t_last)  # the last fix is exactly at the end of the drive
    fixes = []
    for t in times:
        (lat, lon), bearing = along.at(speed * (t - t_first))
        fixes.append({"t": t, "lat": lat, "lon": lon, "speed": speed, "bearing": bearing})
    return fixes, speed


def write_gps_csv(path: Path, fixes: list[dict[str, float]]) -> None:
    """The recorder CSV format (accuracy 5 m, constant)."""
    lines = ["timestamp_sec,lat,lon,accuracy_m,speed_mps,bearing_deg,utc_ms"]
    for f in fixes:
        lines.append(
            f"{f['t']:.3f},{f['lat']:.7f},{f['lon']:.7f},5.0,{f['speed']:.2f},{f['bearing']:.1f},"
            f"{EPOCH_MS + round(f['t'] * 1000)}"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_sidecar(path: Path, video_name: str, gps_name: str, duration_s: float, n_fixes: int, distance_m: float) -> None:
    """The recorder JSON sidecar; the device field says the data is synthetic."""
    sidecar = {
        "format": "road-recorder/1",
        "video": video_name,
        "gps": gps_name,
        "started_utc": datetime.fromtimestamp(EPOCH_MS / 1000, timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z"),
        "duration_sec": round(duration_s, 6),
        "resolution": f"{FRAME_SIZE}x{FRAME_SIZE}",
        "gps_fixes": n_fixes,
        "distance_m": round(distance_m),
        "device": DEVICE,
        "synthetic": True,
        "median_accuracy_m": 5.0,
    }
    path.write_text(json.dumps(sidecar, indent=2) + "\n", encoding="utf-8")


# ---------------------------------------------------------------------------- candidate paths


@dataclass(frozen=True)
class Candidate:
    nodes: list[int]  # the driven node path
    points: list[LatLon]  # its geometry
    length_m: float
    speed_mps: float
    dest_index: int  # index in ``nodes`` of the suggested destination
    alt_ratio: float  # shortest alternative origin->destination length over the driven one


def _alternative_length(graph: RoadGraph, nodes: list[int], limit: float) -> float | None:
    """Length of the shortest route from nodes[0] to nodes[-1] avoiding the driven edges."""
    import networkx as nx

    removed = []
    for a, b in zip(nodes, nodes[1:]):
        key, _ = _edge_choice(graph, a, b)
        removed.append((a, b, key))
        if graph.g.has_edge(b, a, key):
            removed.append((b, a, key))
    view = nx.restricted_view(graph.g, [], removed)
    try:
        length, _ = nx.single_source_dijkstra(view, nodes[0], target=nodes[-1], cutoff=limit, weight=_weight)
    except (nx.NetworkXNoPath, nx.NodeNotFound):
        return None
    return float(length)


def find_candidates(
    graph: RoadGraph,
    schedule: Schedule,
    *,
    seed: int,
    max_alt_ratio: float = 1.6,
    max_starts: int = 150,
    per_start: int = 2,
) -> list[Candidate]:
    """Deterministic candidate drives, best first.

    Each is a shortest path of the road graph whose length lets it be driven at
    ``NOMINAL_SPEED_MPS`` to 1.25 times that over the schedule's duration, with a
    node near the end of the pothole part as destination such that an alternative
    route origin -> destination exists that is at most ``max_alt_ratio`` times as
    long. Sorted by that ratio (smaller first).
    """
    import networkx as nx

    duration = schedule.duration_s
    need = NOMINAL_SPEED_MPS * (duration + 2.0)
    lo, hi = need, 1.25 * need
    rng = random.Random(seed)
    starts = sorted(graph.g.nodes)
    rng.shuffle(starts)
    found: list[Candidate] = []
    for s in starts[:max_starts]:
        dist, paths = nx.single_source_dijkstra(graph.g, s, cutoff=hi, weight=_weight)
        targets = sorted(t for t, d in dist.items() if lo <= d <= hi)
        for u in rng.sample(targets, min(per_start, len(targets))):
            nodes = paths[u]
            points, node_dist = path_polyline(graph, nodes)
            total = node_dist[-1]
            speed = total / (duration + 2.0)
            if speed * schedule.cycle / schedule.fps < 30.0 or speed > 12.0:
                continue
            s_end = speed * (schedule.potholes_end_s + 1.0)
            dest = next((i for i, d in enumerate(node_dist) if d >= s_end + 15.0), None)
            if dest is None or dest >= len(nodes) - 1 or total - node_dist[dest] < 0.4 * (total - s_end):
                continue
            alt = _alternative_length(graph, nodes[: dest + 1], max_alt_ratio * node_dist[dest])
            if alt is None:
                continue
            found.append(Candidate(nodes, points, total, speed, dest, alt / node_dist[dest]))
    found.sort(key=lambda c: (c.alt_ratio, c.nodes[0], c.nodes[-1]))
    return found


