"""Create ONE clearly synthetic demonstration session for route recommendation.

Real forward-facing footage is not available yet, so this script generates a
demonstration that cannot be mistaken for real data:

* The video is built from RDD2022 VALIDATION images only (never the test split):
  pothole images are held on screen long enough to be tracked, separated by
  pothole-free images so that tracks cannot join and consecutive potholes end up
  more than 30 m apart. Every frame carries the caption
  "SYNTHETIC DEMO - images from RDD2022 validation set, GPS trace generated".
* The GPS trace is generated at a constant speed along a real path of the road
  graph (``routing.graph_path``). Potholes appear only in the first part of the
  drive; the rest of the drive is pothole-free, so that the surveyed road has a
  lower pothole rate than the stretch between the suggested end points (the
  route planner charges unsurveyed road an assumed rate, the observed rate
  blended with ``routing.assumed_rate_per_100m``, so a detour over unsurveyed
  road is only chosen when the mapped potholes on the direct stretch outweigh
  that assumption).
* The session is registered with role ``demo`` and ``gps_source`` ``synthetic``,
  processed with the real detector, and the map is rebuilt. The suggested route
  end points go to ``<data_dir>/demo/demo_route.json`` for the web interface.

The result is checked: ``plan_routes`` must give a different route for
avoidance 0 and avoidance 1 between the suggested end points. Other candidate
paths are tried if not; if none works, that is reported honestly.

    python scripts/make_synthetic_demo.py [--config configs/app.yaml] [--seed 7]
        [--n-potholes 13] [--no-process]

It takes the database's process lock, so it refuses to run while the web server
is using the same database. It turns demo mode on (``include_synthetic``); the
synthetic session stays separate from recorded data in every statistic.
"""

