def main(argv: list[str] | None = None, *, detector_factory: Callable[[], Any] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Create the synthetic demonstration session. Do not run it while the web "
        "server is processing jobs on the same database."
    )
    parser.add_argument("--config", default=str(project_root() / "configs" / "app.yaml"))
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--n-potholes", type=int, default=13, help="pothole images to insert (about 12-15)")
    parser.add_argument("--no-process", action="store_true", help="register the session but do not run the detector")
    args = parser.parse_args(argv)

    try:
        cfg = load_app_config(Path(args.config))
        result = run_demo(
            cfg, seed=args.seed, n_potholes=args.n_potholes, process=not args.no_process,
            detector_factory=detector_factory,
        )  # fmt: skip
    except Exception as exc:
        if isinstance(exc, (DemoError, ConfigError)):
            print(f"error: {exc}", file=sys.stderr)
            return 1
        raise
    print()
    print("SYNTHETIC DEMONSTRATION SESSION (not real data)")
    print(f"  session        {result.session_id} ({SESSION_NAME}, role demo, gps_source synthetic)")
    print(f"  files          {result.out_dir}")
    print(
        f"  drive          {result.drive_length_m:.0f} m at {result.speed_mps:.1f} m/s "
        f"({result.speed_mps * 3.6:.0f} km/h), {result.duration_s:.0f} s, {len(result.nodes)} road nodes"
    )
    print(f"  inserted       {result.n_inserted} pothole images")
    if result.n_found is not None:
        print(
            f"  detector found {result.n_found} of {result.n_inserted} inserted pothole images "
            f"(+{result.n_extra_tracks} track(s) on pothole-free images)"
        )
    print(f"  origin         {result.origin['lat']:.6f}, {result.origin['lon']:.6f}")
    print(f"  destination    {result.destination['lat']:.6f}, {result.destination['lon']:.6f}")
    print(f"  routes differ  {result.routes_differ} (avoidance 0 vs 1; candidates tried: {result.candidates_tried})")
    for note in result.notes:
        print(f"  NOTE: {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
